#!/usr/bin/env node
/*
 * Copy brand assets into the public/ directories of all three
 * obs-unified surfaces (web app, docs site, marketing landing).
 *
 * The docs and presence projects are sibling repos to obs-unified,
 * not pnpm workspace members, so they can't import @obs-unified/brand
 * directly — we sync the built files into their public/ instead and
 * commit them as if they were ordinary static assets.
 *
 * Run: node packages/brand/scripts/sync-to-projects.mjs
 *
 * Re-run any time the SVG sources change. The script is idempotent.
 */

import { copyFile, mkdir, readFile, writeFile, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const BRAND = resolve(__dirname, "..");
const REPO_ROOT = resolve(BRAND, "../../..");

/*
 * Each target lists the public/ directory of a consuming project and
 * which files it actually needs. We don't blast every asset into
 * every project — the web app doesn't need an OG card, presence
 * doesn't need a maskable PWA icon, etc.
 */
const TARGETS = [
	{
		name: "obs-unified web app",
		publicDir: resolve(REPO_ROOT, "obs-unified/apps/web/public"),
		files: [
			["favicons/favicon.svg", "favicon.svg"],
			["favicons/favicon.ico", "favicon.ico"],
			["favicons/apple-touch-icon.png", "apple-touch-icon.png"],
			["favicons/icon-192.png", "icon-192.png"],
			["favicons/icon-512.png", "icon-512.png"],
			["favicons/icon-maskable-512.png", "icon-maskable-512.png"],
			["favicons/site.webmanifest", "site.webmanifest"],
			["og/obs-unified.svg", "og.svg"],
			["og/obs-unified.jpg", "og.jpg"],
		],
	},
	{
		name: "obs-unified-docs",
		publicDir: resolve(REPO_ROOT, "obs-unified-docs/public"),
		files: [
			["favicons/favicon.svg", "favicon.svg"],
			["favicons/favicon.ico", "favicon.ico"],
			["favicons/apple-touch-icon.png", "apple-touch-icon.png"],
			["favicons/icon-192.png", "icon-192.png"],
			["favicons/icon-512.png", "icon-512.png"],
			["favicons/site.webmanifest", "site.webmanifest"],
			["og/docs.svg", "og.svg"],
			["og/docs.jpg", "og.jpg"],
		],
	},
	{
		name: "presence",
		publicDir: resolve(REPO_ROOT, "presence/public"),
		files: [
			["favicons/favicon.svg", "favicon.svg"],
			["favicons/favicon.ico", "favicon.ico"],
			["favicons/apple-touch-icon.png", "apple-touch-icon.png"],
			["favicons/icon-192.png", "icon-192.png"],
			["favicons/icon-512.png", "icon-512.png"],
			["favicons/site.webmanifest", "site.webmanifest"],
			["og/presence.svg", "og.svg"],
			["og/presence.jpg", "og.jpg"],
		],
	},
	{
		// presence is vanilla CSS (no Tailwind), so it pulls the
		// tokens.css source straight into its src/ next to style.css.
		// presence/src/style.css does `@import "./tokens.css"`.
		// Stamp is suppressed because we're dropping into a hand-edited
		// src/ directory, not a managed-assets dir.
		name: "presence (CSS tokens)",
		publicDir: resolve(REPO_ROOT, "presence/src"),
		files: [["tokens/tokens.css", "tokens.css"]],
		stamp: false,
	},
	{
		// The GitHub org-profile repo (rendered at github.com/obs-unified).
		// Banner assets only — no favicon/manifest, since this repo's
		// only purpose is to expose profile/README.md.
		name: ".github (org profile)",
		publicDir: resolve(REPO_ROOT, "dot-github/profile"),
		files: [
			["og/profile.svg", "banner.svg"],
			["og/profile-dark.svg", "banner-dark.svg"],
			["og/profile.png", "banner.png"],
			["og/profile-dark.png", "banner-dark.png"],
		],
	},
];

const HEADER = `# Generated by @obs-unified/brand — do not edit.
# Source: packages/brand/ in the obs-unified repo.
# Run \`node packages/brand/scripts/sync-to-projects.mjs\` to refresh.
`;

async function exists(p) {
	try {
		await stat(p);
		return true;
	} catch {
		return false;
	}
}

async function copyOne(src, dst) {
	if (!(await exists(src))) {
		console.warn(`  skip (missing source): ${src.replace(`${REPO_ROOT}/`, "")}`);
		return;
	}
	await mkdir(dirname(dst), { recursive: true });
	await copyFile(src, dst);
	console.log(`  ✓ ${dst.replace(`${REPO_ROOT}/`, "")}`);
}

async function main() {
	for (const target of TARGETS) {
		console.log(`\n[brand] syncing → ${target.name}`);
		if (!(await exists(target.publicDir))) {
			console.warn(`  target public/ does not exist: ${target.publicDir}`);
			continue;
		}
		for (const [from, to] of target.files) {
			await copyOne(resolve(BRAND, from), resolve(target.publicDir, to));
		}
		if (target.stamp !== false) {
			await writeFile(
				resolve(target.publicDir, ".brand-source"),
				`${HEADER}\nSynced ${new Date().toISOString()}\n`,
			);
		}
	}
	console.log("\n[brand] sync complete.\n");
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
