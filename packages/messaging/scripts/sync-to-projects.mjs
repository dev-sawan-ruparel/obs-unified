#!/usr/bin/env node
/*
 * Generate messaging assets for the website, docs, and skills from the
 * canonical manifest. All consumers are part of this monorepo; missing
 * consumers are errors. Run with --check to verify committed assets.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { MANIFEST_PATH, readManifest, WORKSPACE_ROOT } from "./lib.mjs";

const manifestJson = readFileSync(MANIFEST_PATH, "utf8");
const manifest = readManifest();

const tsModule = `// AUTO-GENERATED by @obsunified/messaging sync — do not edit.
// Source of truth: obs-unified/packages/messaging/manifest.json
export const messaging = ${manifestJson.trimEnd()} as const;
export type Messaging = typeof messaging;
`;

const TARGETS = [
	{
		name: "obs-unified-docs",
		file: "apps/docs/messaging.manifest.json",
		content: manifestJson,
	},
	{
		name: "obs-unified-skills",
		file: "skills/messaging.manifest.json",
		content: manifestJson,
	},
	{
		name: "presence (vendored json)",
		file: "apps/website/public/messaging.manifest.json",
		content: manifestJson,
	},
	{
		name: "presence (generated ts)",
		file: "apps/website/src/content/messaging.generated.ts",
		content: tsModule,
	},
];

const check = process.argv.includes("--check");
let stale = 0;
let wrote = 0;

for (const t of TARGETS) {
	const dest = resolve(WORKSPACE_ROOT, t.file);
	const repoRoot = resolve(
		WORKSPACE_ROOT,
		t.file.startsWith("apps/")
			? t.file.split("/").slice(0, 2).join("/")
			: "skills",
	);
	if (!existsSync(repoRoot)) {
		console.error(`messaging:sync ERROR: missing monorepo consumer ${repoRoot}`);
		process.exit(1);
	}
	if (check) {
		const current = existsSync(dest) ? readFileSync(dest, "utf8") : null;
		if (current !== t.content) {
			console.error(`messaging:sync STALE: ${t.file}`);
			stale++;
		}
		continue;
	}
	mkdirSync(dirname(dest), { recursive: true });
	writeFileSync(dest, t.content);
	console.log(`messaging:sync — wrote ${t.file}`);
	wrote++;
}

if (check && stale) {
	console.error(
		`\nmessaging:sync --check failed: ${stale} vendored copy(ies) stale. Run \`pnpm --filter @obsunified/messaging sync\`.`,
	);
	process.exit(1);
}
console.log(
	check
		? "messaging:sync — vendored copies up to date."
		: `messaging:sync — done (${wrote} written). Reference: ${manifest.schemaVersion}`,
);
